export function getCharacter(id) {
  return CHARACTERS.find(c => c.id === id) ?? CHARACTERS[0];
}

export function assignCharacters(players, humanCharacterId) {
  const available = CHARACTERS.filter(c => c.id !== humanCharacterId);
  let aiIdx = 0;
  return players.map(p => {
    if (!p.isAI) return { ...p, characterId: humanCharacterId };
    const char = available[aiIdx % available.length];
    aiIdx++;
    return { ...p, characterId: char.id };
  });
}
