// الكروت الفريدة بدون تكرار id (للتخمين والـ AI)
export const UNIQUE_CARDS = CARDS.filter(
  (c, i, arr) => arr.findIndex(x => x.id === c.id) === i
);

export function buildDeck() {
  const deck = [];
  CARDS.forEach((card, i) => {
    deck.push({ ...card, uid: `${card.id}-${i}` });
  });
  return deck;
}
